bool check_board_version(const uint8_t* otp_ptr) {
    return (otp_ptr[3] == HW_VERSION_MAJOR) &&
           (otp_ptr[4] == HW_VERSION_MINOR) &&
           (otp_ptr[5] == HW_VERSION_VOLTAGE);
}

void system_init() {
    // Reset of all peripherals, Initializes the Flash interface and the Systick.
    HAL_Init();

    // Configure the system clock
    SystemClock_Config();

    // If the OTP is pristine, use the fake-otp in RAM instead
    const uint8_t* otp_ptr = (const uint8_t*)FLASH_OTP_BASE;
    if (*otp_ptr == 0xff) {
        otp_ptr = fake_otp;
    }

    // Ensure that the board version for which this firmware is compiled matches
    // the board we're running on.
    if (!check_board_version(otp_ptr)) {
        for (;;);
    }
}

bool board_init() {
    // Initialize all configured peripherals
    MX_GPIO_Init();
    // CYCCNT also bounds ADC scheduling waits if an ADC stops responding.
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
    MX_DMA_Init();
    MX_ADC1_Init();
    MX_ADC2_Init();
    MX_TIM1_Init();
    MX_TIM8_Init();
    MX_TIM3_Init();
    MX_SPI3_Init();
#if REHAB_ENABLE_NETWORK
    MX_SPI1_Init();
#endif
    MX_ADC3_Init();
    MX_TIM2_Init();
    MX_TIM5_Init();
    MX_TIM13_Init();

    // STOP may disarm Motor immediately; initialize its TIM handle first.
    // GPIO startup and the hardware STOP AND-gate keep GATE low meanwhile.
    rehab::platform::early_init();

    // External interrupt lines are individually enabled in stm32_gpio.cpp
    HAL_NVIC_SetPriority(EXTI0_IRQn, 1, 0);
    HAL_NVIC_EnableIRQ(EXTI0_IRQn);
    HAL_NVIC_SetPriority(EXTI1_IRQn, 1, 0);
    HAL_NVIC_EnableIRQ(EXTI1_IRQn);
    HAL_NVIC_SetPriority(EXTI2_IRQn, 1, 0);
    HAL_NVIC_EnableIRQ(EXTI2_IRQn);
    HAL_NVIC_SetPriority(EXTI3_IRQn, 1, 0);
    HAL_NVIC_EnableIRQ(EXTI3_IRQn);
    HAL_NVIC_SetPriority(EXTI4_IRQn, 1, 0);
    HAL_NVIC_EnableIRQ(EXTI4_IRQn);
    HAL_NVIC_SetPriority(EXTI9_5_IRQn, 1, 0);
    HAL_NVIC_EnableIRQ(EXTI9_5_IRQn);
    HAL_NVIC_SetPriority(EXTI15_10_IRQn, 1, 0);
    HAL_NVIC_EnableIRQ(EXTI15_10_IRQn);

    HAL_NVIC_SetPriority(ControlLoop_IRQn, 5, 0);
    HAL_NVIC_EnableIRQ(ControlLoop_IRQn);

    HAL_NVIC_SetPriority(TIM8_UP_TIM13_IRQn, 0, 0);
    HAL_NVIC_EnableIRQ(TIM8_UP_TIM13_IRQn);

    if (odrv.config_.enable_uart_a) {
        uart_a->Init.BaudRate = odrv.config_.uart_a_baudrate;
        if (odrv.config_.gpio_modes[3] != ODriveIntf::GPIO_MODE_UART_A ||
                odrv.config_.gpio_modes[4] != ODriveIntf::GPIO_MODE_UART_A) {
            odrv.misconfigured_ = true;
        }
        MX_USART2_UART_Init();
    }

    // Unsupported peripherals must never claim reserved extension pins.
    if (odrv.config_.enable_uart_b || odrv.config_.enable_uart_c || odrv.config_.enable_i2c_a) {
        odrv.misconfigured_ = true;
        return false;
    }

    if (odrv.config_.enable_can_a) {
        // The CAN initialization will (and must) init its own GPIOs before the
        // GPIO modes are initialized. Therefore we ensure that the later GPIO
        // mode initialization won't override the CAN mode.
        if (odrv.config_.gpio_modes[15] != ODriveIntf::GPIO_MODE_CAN_A || odrv.config_.gpio_modes[16] != ODriveIntf::GPIO_MODE_CAN_A) {
            odrv.misconfigured_ = true;
        }
    }

    // Ensure that debug halting of the core doesn't leave the motor PWM running
    __HAL_DBGMCU_FREEZE_TIM1();
    __HAL_DBGMCU_FREEZE_TIM8();
    __HAL_DBGMCU_FREEZE_TIM13();

    // GATE stays low until the isolated V1.3 wrapper performs task-context
    // initialization with STOP high, PWM disarmed and its epoch still valid.
    Stm32Gpio{GATE_GPIO_Port, GATE_Pin}.write(false);
    Stm32Gpio{DC_CAL_GPIO_Port, DC_CAL_Pin}.write(false);

    return true;
}

void start_timers() {
    CRITICAL_SECTION() {
        // TIM8 is a scheduling source only, never a power-stage output.
        TIM8->CCER = 0;
        TIM8->BDTR &= ~TIM_BDTR_MOE;
        // Temporarily disable ADC triggers so they don't trigger as a side
        // effect of starting the timers.
        hadc1.Instance->CR2 &= ~(ADC_CR2_JEXTEN);
        hadc2.Instance->CR2 &= ~(ADC_CR2_EXTEN | ADC_CR2_JEXTEN);
        hadc3.Instance->CR2 &= ~(ADC_CR2_EXTEN | ADC_CR2_JEXTEN);

        /*
        * Synchronize TIM1, TIM8 and TIM13 such that:
        *  1. The triangle waveform of TIM1 leads the triangle waveform of TIM8 by a
        *     90° phase shift.
        *  2. Each TIM13 reload coincides with a TIM1 lower update event.
        */
        Stm32Timer::start_synchronously<3>(
            {&htim1, &htim8, &htim13},
            {TIM1_INIT_COUNT, 0, TIM1_INIT_COUNT / 2 /* TIM13 is on a clock that's only have as fast as TIM1 */}
        );

        hadc1.Instance->CR2 |= (ADC_EXTERNALTRIGINJECCONVEDGE_RISING);
        hadc2.Instance->CR2 |= (ADC_EXTERNALTRIGCONVEDGE_RISING | ADC_EXTERNALTRIGINJECCONVEDGE_RISING);
        hadc3.Instance->CR2 |= (ADC_EXTERNALTRIGCONVEDGE_RISING | ADC_EXTERNALTRIGINJECCONVEDGE_RISING);

        __HAL_ADC_CLEAR_FLAG(&hadc1, ADC_FLAG_JEOC);
        __HAL_ADC_CLEAR_FLAG(&hadc2, ADC_FLAG_JEOC);
        __HAL_ADC_CLEAR_FLAG(&hadc3, ADC_FLAG_JEOC);
        __HAL_ADC_CLEAR_FLAG(&hadc1, ADC_FLAG_EOC);
        __HAL_ADC_CLEAR_FLAG(&hadc2, ADC_FLAG_EOC);
        __HAL_ADC_CLEAR_FLAG(&hadc3, ADC_FLAG_EOC);
        __HAL_ADC_CLEAR_FLAG(&hadc1, ADC_FLAG_OVR);
        __HAL_ADC_CLEAR_FLAG(&hadc2, ADC_FLAG_OVR);
        __HAL_ADC_CLEAR_FLAG(&hadc3, ADC_FLAG_OVR);
        
        __HAL_TIM_CLEAR_IT(&htim8, TIM_IT_UPDATE);
        __HAL_TIM_ENABLE_IT(&htim8, TIM_IT_UPDATE);
    }
}

static rehab::platform::PhaseAdcMonitor phase_adc_monitor;

// The control ISR is the sole recorder writer. Fibre only arms while idle,
// or copies one word under a short interrupt guard. Never performs motor I/O.
uint32_t rehab_board_capture_arm() {
    CRITICAL_SECTION() {
        if (axes[0].current_state_ != Axis::AXIS_STATE_IDLE ||
            axes[0].requested_state_ != Axis::AXIS_STATE_UNDEFINED || motors[0].is_armed_) return 1;
        rehab::capture::recorder.arm();
        rehab::capture::active = false;
        return 0;
    }
    return 1;
}
uint32_t rehab_board_capture_word(uint32_t index) {
    CRITICAL_SECTION() { return rehab::capture::recorder.word(index); }
    return 0;
}
static uint32_t capture_float(float value) {
    uint32_t result; memcpy(&result, &value, sizeof(result)); return result;
}
static void capture_begin(uint32_t timestamp) {
    using namespace rehab::capture;
    active = recorder.word(1) == 1 && axes[0].current_state_ == Axis::AXIS_STATE_MOTOR_CALIBRATION;
    if (!active) { recorder.finish(); return; }
    pending = {};
    auto& w = pending.words;
    for (unsigned i = 8; i <= 18; ++i) w[i] = capture_float(NAN);
    w[1] = timestamp;
    w[3] = ((TIM1->BDTR & TIM_BDTR_MOE_Msk) ? 8u : 0u) | (motors[0].is_armed_ ? 16u : 0u);
    w[4] = ADC2->JDR1; w[5] = ADC3->JDR1;
    w[6] = ADC2->SR; w[7] = ADC3->SR;
    w[12] = capture_float(vbus_voltage);
    w[13] = capture_float(motors[0].DC_calib_.phA);
    w[14] = capture_float(motors[0].DC_calib_.phB);
    w[15] = capture_float(motors[0].DC_calib_.phC);
    w[16] = capture_float(motors[0].phase_current_rev_gain_);
    w[17] = capture_float(motors[0].effective_current_lim_ + motors[0].config_.current_lim_margin);
    w[22] = TIM1->BDTR; w[24] = motors[0].armed_state_;
}
static void capture_end() {
    using namespace rehab::capture;
    if (!active) return;
    auto& w = pending.words;
    w[18] = capture_float(motors[0].I_bus_);
    const uint64_t error = static_cast<uint64_t>(motors[0].error_);
    w[19] = static_cast<uint32_t>(error); w[20] = static_cast<uint32_t>(error >> 32);
    w[21] = static_cast<uint32_t>(odrv.error_); w[23] = TIM1->BDTR;
    recorder.push(pending);
    active = false;
}

uint32_t rehab_board_phase_adc_word(unsigned index) {
    CRITICAL_SECTION() {
        return phase_adc_monitor.word(index, HAL_GetTick());
    }
    return 0;
}

static bool fetch_and_reset_adcs(std::optional<Iph_ABC_t>* current0, bool capture_dc = false) {
    bool all_adcs_done = (ADC1->SR & ADC_SR_JEOC) == ADC_SR_JEOC
        && (ADC2->SR & (ADC_SR_EOC | ADC_SR_JEOC)) == (ADC_SR_EOC | ADC_SR_JEOC)
        && (ADC3->SR & (ADC_SR_EOC | ADC_SR_JEOC)) == (ADC_SR_EOC | ADC_SR_JEOC);
    if (!all_adcs_done) {
        if (capture_dc) phase_adc_monitor.record(0, 0, false, false, false, false, HAL_GetTick());
        return false;
    }

    vbus_sense_adc_cb(ADC1->JDR1);

    const uint32_t raw_b = ADC2->JDR1;
    const uint32_t raw_c = ADC3->JDR1;
    if (!capture_dc && rehab::capture::active) {
        rehab::capture::pending.words[4] = raw_b;
        rehab::capture::pending.words[5] = raw_c;
        rehab::capture::pending.words[12] = capture_float(vbus_voltage);
    }
    const bool gate_ready = m0_gate_driver.is_ready();
    bool conversion_valid = false;
    if (gate_ready) {
        std::optional<float> phB = motors[0].phase_current_from_adcval(raw_b);
        std::optional<float> phC = motors[0].phase_current_from_adcval(raw_c);
        if (phB.has_value() && phC.has_value()) {
            conversion_valid = true;
            *current0 = {-*phB - *phC, *phB, *phC};
            if (!capture_dc && rehab::capture::active) rehab::capture::pending.words[3] |= 1u;
        }
    }

    if (capture_dc) phase_adc_monitor.record(raw_b, raw_c, true, gate_ready,
        conversion_valid, (TIM1->BDTR & TIM_BDTR_MOE_Msk) != 0, HAL_GetTick());

    ADC1->SR = ~(ADC_SR_JEOC);
    ADC2->SR = ~(ADC_SR_EOC | ADC_SR_JEOC | ADC_SR_OVR);
    ADC3->SR = ~(ADC_SR_EOC | ADC_SR_JEOC | ADC_SR_OVR);

    return true;
}

namespace {
// STM32F405 has no data cache. DMA writes halfwords, each voltage read is one
// aligned halfword load; no multi-channel snapshot is promised by this API.
alignas(4) uint16_t general_adc_samples[3] = {};
bool general_adc_started = false;
constexpr uint32_t general_adc_channels[3] = {1, 8, 15};
}

bool rehab_board_adc_channel_valid(uint32_t channel) {
    return channel == 1 || channel == 8 || channel == 15;
}

float rehab_board_adc_voltage(uint32_t channel) {
    if (!general_adc_started) { return -1.0f; }
    for (size_t i = 0; i < 3; ++i) {
        if (general_adc_channels[i] == channel) {
            const volatile uint16_t* samples = general_adc_samples;
            return samples[i] * (3.3f / 4096.0f);
        }
    }
    return -1.0f;
}

bool rehab_board_start_general_adc() {
    // ADC1 injected bus-voltage conversion remains configured by MX_ADC1_Init.
    general_adc_started = false;
    hadc1.Init.ScanConvMode = ENABLE;
    hadc1.Init.ContinuousConvMode = ENABLE;
    hadc1.Init.NbrOfConversion = 3;
    hadc1.Init.DMAContinuousRequests = ENABLE;
    if (HAL_ADC_Init(&hadc1) != HAL_OK) { return false; }
    ADC_ChannelConfTypeDef config{};
    config.SamplingTime = ADC_SAMPLETIME_15CYCLES;
    for (size_t i = 0; i < 3; ++i) {
        config.Channel = general_adc_channels[i];
        config.Rank = i + 1;
        if (HAL_ADC_ConfigChannel(&hadc1, &config) != HAL_OK) { return false; }
    }
    general_adc_started = HAL_ADC_Start_DMA(&hadc1,
        reinterpret_cast<uint32_t*>(general_adc_samples), 3) == HAL_OK;
    return general_adc_started;
}

