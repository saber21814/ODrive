#!/usr/bin/env python3
"""Keep VS Code on the actual V1.2 ARM commands and isolated generated headers.

The installed Windows tup predates `compiledb`/`commandline`. Read its command
nodes without changing the database or invoking its default build operation.
"""
import argparse
import json
import pathlib
import shlex
import shutil
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
EDITOR = ROOT/'build/rehab/editor'
HEADER_NAMES = ('interfaces.hpp', 'function_stubs.hpp', 'endpoints.hpp', 'type_info.hpp')


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp=path.with_suffix(path.suffix+'.tmp')
    temp.write_text(json.dumps(value, indent=2)+'\n', encoding='utf-8')
    temp.replace(path)


def capture(board='v12'):
    """Call after a successful FULL build, before restoring tup.config."""
    global EDITOR
    EDITOR=ROOT/('build/rehab/v13/editor' if board=='v13' else 'build/rehab/editor')
    with sqlite3.connect((ROOT/'.tup/db').resolve().as_uri()+'?mode=ro', uri=True) as db:
        commands=[row[0] for row in db.execute(
            "SELECT name FROM node WHERE type=1 AND name LIKE '%arm-none-eabi-% -c %'")]
    entries={}
    for command in commands:
        args=shlex.split(command)
        if '-c' not in args: continue
        source=(ROOT/args[args.index('-c')+1]).resolve()
        if source.suffix.lower() not in ('.c','.cpp','.cc'): continue
        compiler=shutil.which(args[0])
        if not compiler: raise RuntimeError('ARM compiler not found: '+args[0])
        if '-DREHAB_V12=1' not in args or '-DREHAB_STAGE=6' not in args:
            raise RuntimeError('Editor export requires the FULL V1.2 command database.')
        if ('-DREHAB_V13=1' in args) != (board=='v13'):
            raise RuntimeError('Editor export board does not match the compile commands.')
        args[0]=pathlib.Path(compiler).as_posix()
        # Same generated bytes as the real build, isolated from later v3 builds.
        args.insert(1, '-I'+EDITOR.as_posix())
        entries[source.as_posix()]={'directory':ROOT.as_posix(), 'file':source.as_posix(), 'arguments':args}
    main=(ROOT/'MotorControl/main.cpp').as_posix()
    if main not in entries: raise RuntimeError('Missing real main.cpp compile command.')
    if not all((ROOT/'autogen'/name).is_file() for name in HEADER_NAMES):
        raise RuntimeError('Missing generated interface headers.')
    if 'RehabStatusIntf' not in (ROOT/'autogen/interfaces.hpp').read_text():
        raise RuntimeError('Generated headers belong to the original board.')
    (EDITOR/'autogen').mkdir(parents=True, exist_ok=True)
    for name in HEADER_NAMES:
        shutil.copy2(ROOT/'autogen'/name, EDITOR/'autogen'/name)
    firmware_count=len(entries)
    # Host test files get their own real test flags and mocks; never put mocks
    # on the firmware include path or guess ARM flags for host test translation units.
    import test as host_tests
    host_compiler=shutil.which('g++')
    if host_compiler:
        for suite in host_tests.specifications(False):
            if suite.get('python'): continue
            flags=[*suite['flags'], *('-D'+d for d in suite['definitions']),
                   *('-I'+p for p in suite['includes'])]
            for name in suite['sources']:
                source=(ROOT/name).resolve().as_posix()
                if source in entries: continue
                entries[source]={'directory':ROOT.as_posix(), 'file':source,
                    'arguments':[pathlib.Path(host_compiler).as_posix(), *flags, '-c', source]}
    write_json(EDITOR/'compile_commands.json', list(entries.values()))
    write_json(EDITOR/'context.json', {'profile':'full', 'board':board, 'firmware_units':firmware_count,
                                     'host_units':len(entries)-firmware_count})
    print(f'Editor context: {firmware_count} ARM + {len(entries)-firmware_count} host units; isolated V1.2 headers.')


def configure():
    entries=json.loads((EDITOR/'compile_commands.json').read_text())
    main=next(e for e in entries if e['file']==(ROOT/'MotorControl/main.cpp').as_posix())
    args=main['arguments']
    includes=[('${workspaceFolder}/'+pathlib.Path(a[2:]).as_posix())
              if not pathlib.Path(a[2:]).is_absolute() else pathlib.Path(a[2:]).as_posix()
              for a in args if a.startswith('-I')]
    includes=list(dict.fromkeys(includes))
    config={'name':'ODrive Rehab V1.2', 'compilerPath':args[0],
            'compileCommands':'${workspaceFolder}/build/rehab/editor/compile_commands.json',
            'includePath':includes, 'defines':[a[2:] for a in args if a.startswith('-D')],
            'compilerArgs':['-mthumb','-mcpu=cortex-m4','-mfpu=fpv4-sp-d16','-mfloat-abi=hard'],
            'intelliSenseMode':'windows-gcc-arm', 'cStandard':'c99', 'cppStandard':'c++17',
            'browse':{'path':['${workspaceFolder}/MotorControl','${workspaceFolder}/Rehab',
                       '${workspaceFolder}/Board/rehab_v12','${workspaceFolder}/Drivers',
                       '${workspaceFolder}/communication','${workspaceFolder}/fibre-cpp/include'],
                      'limitSymbolsToIncludedHeaders':True}}
    backup=ROOT/'build/rehab/editor-before'
    backup.mkdir(parents=True, exist_ok=True)
    for name in ('c_cpp_properties.json','settings.json','tasks.json'):
        path=ROOT/'.vscode'/name
        if path.exists() and not (backup/name).exists(): shutil.copy2(path,backup/name)
    write_json(ROOT/'.vscode/c_cpp_properties.json',{'configurations':[config],'version':4})
    settings=json.loads((ROOT/'.vscode/settings.json').read_text(encoding='utf-8'))
    settings.update({'C_Cpp.intelliSenseEngine':'Default','C_Cpp.errorSquiggles':'enabled',
                     'C_Cpp.maxConcurrentThreads':1,'C_Cpp.workspaceParsingPriority':'low',
                     'C_Cpp.intelliSenseMemoryLimit':768})
    settings.setdefault('files.watcherExclude',{}).update({
        '**/.tup/**':True,'**/build/obj/**':True,'**/build/rehab/tests/**':True})
    write_json(ROOT/'.vscode/settings.json', settings)
    print('VS Code: explicit ARM compiler, per-file commands, no recursive mock includes, one parsing thread.')


def refresh_host():
    """Refresh test-only entries without touching the frozen FULL ARM context."""
    import test as host_tests
    compiler=shutil.which('g++')
    if not compiler: raise RuntimeError('Host g++ was not found.')
    database=EDITOR/'compile_commands.json'
    entries={entry['file']:entry for entry in json.loads(database.read_text())}
    test_root=(ROOT/'Tests').as_posix()+'/'
    entries={name:entry for name,entry in entries.items() if not name.startswith(test_root)}
    for suite in host_tests.specifications(False):
        if suite.get('python'): continue
        flags=[*suite['flags'], *('-D'+d for d in suite['definitions']), *('-I'+p for p in suite['includes'])]
        for name in suite['sources']:
            source=(ROOT/name).resolve().as_posix()
            if source in entries: continue
            entries[source]={'directory':ROOT.as_posix(),'file':source,
                'arguments':[pathlib.Path(compiler).as_posix(),*flags,'-c',source]}
    write_json(database,list(entries.values()))
    context=json.loads((EDITOR/'context.json').read_text())
    context['host_units']=len(entries)-context['firmware_units']
    write_json(EDITOR/'context.json',context)
    print('Refreshed host test commands; FULL ARM commands and generated headers retained.')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--configure',action='store_true')
    p.add_argument('--refresh-host',action='store_true')
    a=p.parse_args()
    if a.refresh_host: refresh_host()
    elif a.configure: configure()
    else: capture()
